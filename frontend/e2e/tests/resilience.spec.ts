import { expect, test } from '@playwright/test'

test('X01: browser refresh restores the household draft', async ({ page }) => {
  await page.goto('./')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.getByRole('button', { name: /Explore The Amina Family/ }).first().click()
  await page.getByRole('button', { name: /Add task/ }).click()
  await expect(page.getByText('New household task').first()).toBeVisible()
  await page.reload()
  await expect(page.getByText('New household task').first()).toBeVisible()
})

test('X02: backend outage is reported honestly and computation is disabled', async ({ page }) => {
  await page.route('**/v1/**', (r) => r.abort())
  await page.goto('./')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await expect(page.getByText('API offline').first()).toBeVisible()
  await expect(page.getByText(/Backend not reachable/)).toBeVisible()
  await page.getByRole('button', { name: /Explore The Amina Family/ }).first().click()
  await expect(page.getByText(/Backend unreachable/).first()).toBeVisible()
  await page.getByRole('link', { name: /Disrupt/ }).click()
  await page.getByRole('button', { name: /^Amina unavailable/ }).click()
  await page.getByRole('button', { name: 'Confirm all' }).click()
  await expect(page.getByRole('button', { name: 'Run scenario' }).last()).toBeDisabled()
  await page.getByRole('link', { name: /Evaluate/ }).click()
  await expect(page.getByText('Benchmark not yet executed.')).toBeVisible()
})

test('X03: keyboard navigation, landmarks, reduced motion and graph text alternative', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('./')
  await expect(page.getByRole('navigation', { name: 'Primary' })).toBeVisible()
  await expect(page.getByRole('link', { name: /Launch/ }).first()).toHaveAttribute('aria-current', 'page')
  await page.keyboard.press('Tab')
  const focused = await page.evaluate(() => document.activeElement?.tagName)
  expect(['A', 'BUTTON']).toContain(focused)
  await page.getByRole('button', { name: /Explore The Amina Family/ }).first().focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#\/network/)
  await expect(page.locator('html')).toHaveAttribute('data-reduced-motion', 'true')
  await page.getByText(/Text alternative to the graph/).click()
  await expect(page.getByRole('cell', { name: /School pickup/ }).first()).toBeVisible()
})
