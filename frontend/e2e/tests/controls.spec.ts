import { expect, test, type Page } from '@playwright/test'

async function begin(page: Page, card = /Explore The Amina Family/) {
  await page.goto('./')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.getByRole('button', { name: card }).first().click()
  await expect(page).toHaveURL(/#\/network/)
  await expect(page.getByText('0 errors · 0 warnings')).toBeVisible()
}
const go = (p: Page, n: RegExp) => p.getByRole('link', { name: n }).first().click()

async function recovered(page: Page) {
  await go(page, /Disrupt/)
  await page.getByRole('button', { name: /^Amina unavailable/ }).click()
  await page.getByRole('button', { name: 'Confirm all' }).click()
  await page.getByRole('button', { name: 'Run scenario' }).last().click()
  await expect(page).toHaveURL(/#\/cascade/)
  await go(page, /Recover/)
  await expect(page.getByText('Verified complete recovery').first()).toBeVisible()
}

test('Configure Household: edit with validation, then open in Family Network', async ({ page }) => {
  await page.goto('./')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await page.getByRole('button', { name: 'Configure Household' }).click()
  const dlg = page.getByRole('dialog')
  await dlg.getByRole('button', { name: 'The Amina Family' }).click()
  await dlg.getByRole('button', { name: 'Noura' }).click()
  await dlg.getByLabel('Name', { exact: true }).fill('Noura Z')
  await expect(dlg.getByText(/passes backend validation/)).toBeVisible()
  // an impossible task window is allowed but warned about; an unknown reference would block "Open"
  await dlg.getByRole('tab', { name: 'Tasks' }).click()
  await dlg.getByRole('button', { name: 'Add task' }).click()
  await expect(dlg.getByText(/passes backend validation/)).toBeVisible()
  await dlg.getByRole('button', { name: 'Open in Family Network' }).click()
  await expect(page).toHaveURL(/#\/network/)
  await expect(page.getByText('Noura Z').first()).toBeVisible()
})

test('Manual disruption: create, edit and remove events; a resource event runs', async ({ page }) => {
  await begin(page)
  await go(page, /Disrupt/)
  await page.getByRole('button', { name: 'New event' }).click()
  await page.getByLabel('Event type').selectOption('resource_unavailable')
  await expect(page.getByRole('button', { name: 'Stage event' })).toBeDisabled()          // no entity chosen yet
  await page.getByLabel('Family sedan').check()
  await page.getByRole('button', { name: 'Stage event' }).click()
  await expect(page.getByText('needs confirmation')).toBeVisible()
  await page.getByRole('button', { name: 'Edit' }).click()
  await page.getByLabel('Reason (optional)').fill('Sedan in the garage')
  await page.getByRole('button', { name: 'Stage event' }).click()
  await expect(page.getByText(/Sedan in the garage/)).toBeVisible()
  await page.getByRole('button', { name: 'Remove event' }).click()
  await expect(page.getByText(/No events yet/)).toBeVisible()
  await page.getByRole('button', { name: 'New event' }).click()
  await page.getByLabel('Event type').selectOption('resource_unavailable')
  await page.getByLabel('Family sedan').check()
  await page.getByRole('button', { name: 'Stage event' }).click()
  await page.getByRole('button', { name: 'Confirm all' }).click()
  await page.getByRole('button', { name: 'Run scenario' }).last().click()
  await expect(page).toHaveURL(/#\/cascade/)
  await go(page, /Recover/)
  await expect(page.getByText('Valid partial plan — human intervention required').first()).toBeVisible()   // no vehicle → pickup uncovered
})

test('Recovery: pin an assignee, find another arrangement, return to the original schedule', async ({ page }) => {
  await begin(page)
  await recovered(page)
  const table = page.getByRole('table', { name: 'Proposed assignments' })
  await table.locator('tr').filter({ hasText: 'Homework assistance' }).getByRole('button', { name: /Modify/ }).click()
  const dlg = page.getByRole('dialog')
  await dlg.getByLabel('Assignee').selectOption({ label: 'Khalid' })        // Khalid has no homework skill → must come back uncovered
  await dlg.getByRole('button', { name: /Re-optimize with this constraint/ }).click()
  await expect(page.getByText('Active constraints')).toBeVisible()
  await expect(table.locator('tr').filter({ hasText: 'Homework assistance' })).toContainText('UNCOVERED')
  await page.getByRole('button', { name: 'Clear constraints' }).click()
  await expect(table.locator('tr').filter({ hasText: 'Homework assistance' })).toContainText('Noura')
  await page.getByRole('button', { name: /Find another distinct arrangement/ }).click()
  await expect(page.getByText(/showing an alternative arrangement/)).toBeVisible()
  await page.getByRole('button', { name: 'Back to all strategies' }).click()
  await page.getByRole('button', { name: 'Return to original schedule' }).click()
  await expect(page.getByRole('button', { name: 'Show recovery plan' })).toBeVisible()
})

test('Futures: vehicle what-if, then Apply scenario replaces the main scenario', async ({ page }) => {
  await begin(page)
  await recovered(page)
  await go(page, /Futures/)
  await page.locator('#f-r').selectOption({ label: 'Family sedan' })
  await page.getByRole('button', { name: 'Make unavailable' }).click()
  await expect(page.getByText(/Household variables modified|\+ Resource unavailable/)).toBeVisible()
  await page.getByRole('button', { name: 'Reset' }).click()                       // Reset discards the staged change...
  await expect(page.getByText(/same as reference/)).toBeVisible()
  await page.getByRole('button', { name: 'Make unavailable' }).click()            // ...and it can be staged again
  await page.getByRole('button', { name: 'Run counterfactual' }).click()
  await expect(page.getByText(/Different result: School pickup/)).toBeVisible({ timeout: 30000 })
  await page.getByRole('button', { name: 'Apply scenario' }).click()
  await expect(page).toHaveURL(/#\/recovery/, { timeout: 30000 })
  await expect(page.getByText(/Critical responsibilities uncovered/)).toBeVisible()
})

test('Evaluation Lab: run the suite, replay a case, run the language benchmark, export', async ({ page }) => {
  await page.goto('./')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await go(page, /Evaluate/)
  await expect(page.getByText('Benchmark not yet executed.')).toBeVisible()
  await page.getByRole('button', { name: 'Run benchmark suite' }).click()
  await expect(page.getByText('Passed', { exact: true })).toBeVisible({ timeout: 120000 })
  await expect(page.getByText('Failed', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Benchmark Scenarios' }).click()
  await page.locator('summary').filter({ hasText: 'T02' }).first().click()
  await page.getByRole('button', { name: 'Replay scenario' }).first().click()
  await expect(page.getByText(/reproduced exactly/)).toBeVisible({ timeout: 60000 })
  await page.getByRole('tab', { name: 'AI Interpretation' }).click()
  await page.getByRole('button', { name: /Run rule parser on held-out set/ }).click()
  await expect(page.getByText('Exact match', { exact: true })).toBeVisible({ timeout: 60000 })
  const [dl] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'JSON' }).click()])
  expect(dl.suggestedFilename()).toBe('domino-benchmark.json')
  await page.getByRole('button', { name: 'Open methodology' }).click()
  await expect(page.getByRole('dialog').getByText(/Each benchmark case is a data file/)).toBeVisible()
})
